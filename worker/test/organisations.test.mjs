test('organisation migration preserves legacy project IDs, settings, goals, users and event history', () => {
 const db = new DatabaseSync(':memory:');
 for(const m of ['0001_init','0002_local_time','0003_auth']) db.exec(readFileSync(new URL(`../../migrations/${m}.sql`,import.meta.url),'utf8'));
 db.exec(`INSERT INTO sites (id,name,domain,kind,currency,created,goals,funnel,timezone) VALUES ('legacy','Legacy','legacy.example','docs','$','2026-01-01','[]','{}','Asia/Tokyo');
 INSERT INTO events (site_id,at,day,type,path,source,country,device,browser,visitor_id,session_id) VALUES ('legacy',1,'1970-01-01','pageview','/','Direct','Unknown','Desktop','Chrome','v','s');`);
 db.exec("INSERT INTO auth_users (id,email,role,created_at) VALUES ('owner','owner@example.com','admin',1)");
 const user=db.prepare('SELECT * FROM auth_users').get();
 const before=db.prepare('SELECT * FROM sites').get();const event=db.prepare('SELECT * FROM events').get();
 db.exec(readFileSync(new URL('../../migrations/0004_organisations.sql',import.meta.url),'utf8'));
 const after=db.prepare('SELECT * FROM sites').get(); assert.equal(after.organisation_id,'default'); delete after.organisation_id;
 assert.deepEqual(db.prepare('SELECT * FROM auth_users').get(),user);
 assert.deepEqual(after,before); assert.deepEqual(db.prepare('SELECT * FROM events').get(),event);
 assert.throws(()=>db.exec("DELETE FROM organisations WHERE id='default'"));
 db.close();
});

test('UTC organisation reports scope projects, filters, boundaries, empty rows and comparisons without cross-project deduplication',async()=>{
 const {sql,db}=memorySql();const now=Date.parse('2026-11-04T12:00Z');
 await addSite(sql,'one','one.example','docs','Asia/Tokyo'); await addSite(sql,'two','two.example','store','America/New_York');
 const org=await saveOrganisation(sql,{name:'Other'},now);
 const empty=await saveOrganisation(sql,{name:'Empty'},now);
 const outsider=await createSite(sql,{name:'Outside',domain:'outside.example',kind:'docs',organisationId:org.id},now);
 const unused=await createSite(sql,{name:'Unused',domain:'unused.example',kind:'docs'},now);
 const insert=(id,at,day,visitor,source='Direct',path='/')=>sql.run(`INSERT INTO events (site_id,at,day,type,path,source,country,device,browser,visitor_id,session_id) VALUES (?,?,?,'pageview',?,?,'Unknown','Desktop','Chrome',?,?)`,[id,Date.parse(at),day,path,source,visitor,visitor+day]);
 await insert('one','2026-11-02T23:59:59Z','2026-11-03','a');
 await insert('one','2026-11-03T00:00:00Z','2026-11-03','a');
 await insert('one','2026-11-03T23:59:59Z','2026-11-04','b','Search','/checkout');
 await insert('two','2026-11-03T12:00:00Z','2026-11-03','a');
 await insert('two','2026-11-03T12:01:00Z','2026-11-03','a');
 await insert('two','2026-11-04T00:00:00Z','2026-11-03','c');
 await insert(outsider.id,'2026-11-03T12:00:00Z','2026-11-03','outside');
 const query=(extra={})=>parseOrganisationQuery(new URLSearchParams({from:'2026-11-03',to:'2026-11-03',cmpFrom:'2026-11-02',cmpTo:'2026-11-02',...extra}));
 const report=await organisationReport(sql,'default',query());
 assert.deepEqual(report.main.measurement,{visits:2,bounces:1,measuredVisits:0,visibleMs:0,bounceRate:0.5,duration:null});
 assert.deepEqual(report.main.totals,{pageviews:4,visitorDays:3}); assert.equal(report.prev.totals.pageviews,1);
 assert.equal(report.main.projects.find(p=>p.id===unused.id).pageviews,0);assert.equal(report.main.projects.length,3);
 assert.deepEqual((await organisationReport(sql,'default',query({f:'source:Search'}))).main.totals,{pageviews:1,visitorDays:1});
 assert.equal((await organisationReport(sql,'default',query({f:'page:/checkout'}))).main.totals.pageviews,1);
 assert.equal((await organisationReport(sql,empty.id,query())).main.buckets[0].pageviews,0);
 await assert.rejects(organisationReport(sql,'absent',query()),e=>e.status===404);
 assert.throws(()=>query({from:'2026-99-99'}),e=>e.status===400);
 assert.throws(()=>query({from:'2026-11-04'}),e=>e.status===400);
 await assert.rejects(updateSite(sql,'one',{organisationId:'missing'},now),e=>e.status===404);
 await assert.rejects(deleteSite(sql,'one',now),e=>e.status===409);
 await updateSite(sql,'one',{organisationId:org.id},now);
 assert.equal((await getSite(sql,'one',now)).timezone,'Asia/Tokyo');
 assert.equal((await organisationReport(sql,'default',query())).main.totals.pageviews,2);
 assert.equal((await organisationReport(sql,org.id,query())).main.totals.pageviews,3);
 await deleteSite(sql,unused.id,now);
 assert.equal((await sql.all('SELECT COUNT(*) AS n FROM events'))[0].n,7);
 db.close();
});
